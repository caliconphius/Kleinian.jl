"""
`inverse_permutation(X::AbstractVector{Int})`
takes a permutation σ of {1,...,n}, specified as the vector `[σ(1), ..., σ(n)]` and returns the inverse permutation σ⁻¹ in the same format.
"""
function inverse_permutation(X::AbstractVector{Int})
	Y = Vector{Int}(undef, length(X))
	for i ∈ eachindex(X)
		Y[X[i]] = i
	end
	return Y
end

