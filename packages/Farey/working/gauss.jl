### Generators ###

"""
`AbstractBarGen{T}` 
is an alias for AbstractVector{T}. It is used to unify vectors of simples and views on them.
"""
AbstractBarGen{T} = AbstractVector{T}

"""
`BarGen{T}`
is an alias for Vector{T}. It is the type of generators of the bar resolution of B.
"""
BarGen{T} = Vector{T}

"""
`one(::Type{BarGen{T}}) where T`
returns the unit of type `BarGen{T}`, i.e. the empty vector `T[]`.
"""
function one(::Type{BarGen{T}}) where T
    return T[]
end

"""
`sprint(B::GarsideMonoid{T}, x::AbstractBarGen{T}) where T`
returns a string representing the vector `x` of simples as a concatenation `[σ₁|…|σₙ]` where `σᵢ` is the result of `sprint(B,x[i])`.
"""
function sprint(B::GarsideMonoid{T}, x::AbstractBarGen{T}) where T
	return "[" * join((sprint(B,σ) for σ ∈ x), "|") * "]"
end

"""
`one(::Type{BarGen{T}}) where T`
returns the unit of type `BarGen{T}`, i.e. the empty vector `T[]`.
"""
function one(::Type{BarGen{T}}) where T
    return T[]
end

"""
`·(x::AbstractBarGen{T}, y::AbstractBarGen{T}) where T`
returns the vector `[x₁|…|xₘ₋₁|xₘ*y₁|y₂|…|yₙ]` if `x=[x₁|…|xₘ]` and `y=[y₁|…|yₙ]`.
"""
function ·(x::AbstractBarGen{T}, y::AbstractBarGen{T}) where T
	m = length(x)
	n = length(y)
	return T[ 
		i<m ? x[i] : 
		i==m ? x[m] * y[1] :
		y[i-m+1]
		for i ∈ 1:m+n-1
	]
end

"""
`|(x::AbstractBarGen{T}, y::AbstractBarGen{T}) where T`
returns the vector `[x₁|…|xₘ₋₁|xₘ|y₁|y₂|…|yₙ]` if `x=[x₁|…|xₘ]` and `y=[y₁|…|yₙ]`.
"""
function |(x::AbstractBarGen{T}, y::AbstractBarGen{T}) where T
	m = length(x)
	n = length(y)
	return T[ i ≤ m ? x[i] : y[i-m] for i ∈ 1:m+n]
end

"""
`|(x::AbstractBarGen{T}, σ::T) where T`
returns the vector `[x₁|…|xₘ₋₁|xₘ|σ]` if `x=[x₁|…|xₘ]`.
"""
function |(x::AbstractBarGen{T}, σ::T) where T
	n = length(x)
	return T[ i ≤ n ? x[i] : σ for i ∈ 1:n+1]
end

"""
`⊙(x::AbstractBarGen{T}, σ::T, y::AbstractBarGen{T}) where T`
returns the vector `[x₁|…|xₘ|σ*y₁|y₂|…|yₙ]` if `x=[x₁|…|xₘ]` and `y=[y₁|…|yₙ]`. Assumes `y≠[]`.
"""
function ⊙(x::AbstractBarGen{T}, σ::T, y::AbstractBarGen{T}) where T
	m = length(x)
	n = length(y)
	return T[
		i≤m ? x[i] :
		i==m+1 ? σ * y[1] :
		y[i-m]
		for i ∈ 1:m+n
	]
end

"""
`⊙(x::AbstractBarGen{T}, σ::T, τ::T) where T`
returns the vector `[x₁|…|xₘ|σ*τ]` if `x=[x₁|…|xₘ]`.
"""
function ⊙(x::AbstractBarGen{T}, σ::T, τ::T) where T
	n = length(x)
	return T[ i≤n ? x[i] : σ*τ for i ∈ 1:n+1 ]
end


### Elements of the free (set-theoretic) T-bimodule over BarGen{T}. In practice, we only need elements of the form σxτ for σ,τ simples ###

"""
`BarWord{T}` is the type of elements of the free (set-theoretic) `T`-bimodule over `BarGen{T}`, i.e. elements of the form `u=σxτ` where `σ` and `τ` are simples, and `x` is a vector of simples. The values of `σ`, `x` and `τ` can respectively be accessed by the fields `u.left`, `u.gen` and `u.right`.
"""
struct BarWord{T}
    left::T
    gen::BarGen{T} # remplacer par un vecteur de T si BarGen est un struct
    right::T
end
function hash(u::BarWord{T}, h::UInt) where T
	return hash(u.right, hash(u.gen, hash(u.left, hash(:BarWord{T}, h))))
end
function ==(u::BarWord{T}, v::BarWord{T}) where T 
	return isequal(u.left, v.left) && isequal(u.gen, v.gen) && isequal(u.right, v.right)
end

"""
`isless(u::BarWord{T}, v::BarWord{T}) where T`
compares `u` and `v`, first by their `gen` field, then their `left` field, and finally their `right` field.
"""
function isless(u::BarWord{T}, v::BarWord{T} ; lt=<) where T
	return isless_deglex(u.gen, v.gen ; lt) || (
		u.gen == v.gen && (
			u.left < v.left || (
				u.left == v.left && u.right < v.right
			)
		)
	)
end

"""
`BarWord(x::AbstractBarGen{T}) where T`
returns the element `1x1`.
"""
function BarWord(x::AbstractBarGen{T}) where T
    return BarWord{T}(one(T), x, one(T))
end

"""
`sprint(B::GarsideMonoid{T}, u::BarWord{T}) where T` 
returns a string representing `u`, namely `"σ[x₁|…|xₙ]τ"` if `"σ"` is the result of `sprint(B,u.left)`, `"[x₁|…|xₙ]` is the one of `sprint(B,u.gen)`, and `"τ"` the one of `sprint(B,u.right)`.
"""
function sprint(B::GarsideMonoid{T}, u::BarWord{T}) where T 
    return sprint(B, u.left) * sprint(B, u.gen) * sprint(B, u.right)
end

"""
`*(σ::T, u::BarWord{T}) where T`
returns the left action of `σ` on `u`, i.e. `στ₁[x₁|…|xₙ]τ₂` if `u=τ₁[x₁|…|xₙ]τ₂`.
"""
function *(σ::T, u::BarWord{T}) where T
    return BarWord(σ * u.left, u.gen, u.right)
end

"""
`*(u::BarWord{T}, σ::T) where T`
returns the right action of `σ` on `u`, i.e. `τ₁[x₁|…|xₙ]τ₂σ` if `u=τ₁[x₁|…|xₙ]τ₂`.
"""
function *(u::BarWord{T}, σ::T) where T
    return BarWord(u.left, u.gen, u.right * σ)
end

"""
`*(σ::T, u::BarWord{T}, τ::T) where T`
returns the left action of `σ` and right action of `τ` on `u`, i.e. `σω₁[x₁|…|xₙ]ω₂τ` if `u=ω₁[x₁|…|xₙ]ω₂`.
"""
function *(σ::T, u::BarWord{T}, τ::T) where T
    return BarWord(σ * u.left, u.gen, u.right * τ)
end

"""
`⊙(u::BarWord{T}, y::AbstractBarGen{T}) where T`
returns `σ[x₁|…|xₘ|τ*y₁|…|yₙ]` if `u=σ[x₁|…|xₘ]τ` and `y=[y₁|…|yₙ]`. Assumes `y≠[]`.
"""
function ⊙(u::BarWord{T}, y::AbstractBarGen{T}) where T
	return BarWord(u.left, ⊙(u.gen, u.right, y), one(T))
end

"""
`⊙(u::BarWord{T}, σ::T) where T`
returns `x₀[x₁|…|xₘ|xₘ₊₁*σ]` if `u=x₀[x₁|…|xₘ]xₘ₊₁`
"""
function ⊙(u::BarWord{T}, σ::T) where T
	# return BarWord(u.left, ⊙(u.gen, u.right, σ), one(T))
	return BarWord(u.left, u.gen | (u.right * σ), one(T))
end


### Terms of the free ZT-bimodule over BarGen{T} ###

"""
`BarTerm{T}` is the type of elements of the free Z`T`-bimodule over `BarGen{T}`, i.e. elements of the form `λu` where `λ` is an integer and `u` is a `BarWord{T}`. The values of `λ` and `u` can respectively be accessed by the fields `t.coef` and `t.word`.
"""
struct BarTerm{T}
    coef::Int
    word::BarWord{T}
end
function hash(t::BarTerm{T}, h::UInt) where T
	return hash(t.word, hash(t.coef, hash(:BarTerm{T}, h)))
end
function ==(s::BarTerm{T}, t::BarTerm{T}) where T 
	return isequal(s.coef, t.coef) && isequal(s.word, t.word)
end

"""
`isless(s::BarTerm{T}, t::BarTerm{T}) where T`
compares `s` and `t` according to their `word` field.
"""
function isless(s::BarTerm{T}, t::BarTerm{T} ; lt=<) where T
	return isless(s.word, t.word ; lt=<)
end

"""
`BarTerm(u::BarWord{T}) where T `
returns the term `1u`.
"""
function BarTerm(u::BarWord{T}) where T 
    return BarTerm{T}(1, u)
end

"""
`sprint(B::GarsideMonoid{T}, t::BarTerm{T}) where T`
returns a string formed by the string `sprint(B,t.word)`, prefixed with `+`, `-` or `+ t.coef` depending on the value of the latter.
"""
function sprint(B::GarsideMonoid{T}, t::BarTerm{T}) where T
    λ = t.coef
    w = sprint(B, t.word)
    if λ == 1
        return " + $(w)"
    elseif λ == -1
        return " - $(w)"
    else        
        return " + $(λ)·$(w)"
    end
end

"""
`*(λ::Int, t::BarTerm)`
returns the term `λ t.coef` `t.word` 
"""
function *(λ::Int, t::BarTerm)
    return BarTerm(λ * t.coef, t.word)
end

"""
`*(σ::T, t::BarTerm{T}) where T`
returns the term `t.coef` `σ * t.word` 
"""
function *(σ::T, t::BarTerm{T}) where T
    return BarTerm(t.coef, σ * t.word)
end

"""
`*(t::BarTerm{T}, τ::T) where T`
returns the term `t.coef` `t.word * τ` 
"""
function *(t::BarTerm{T}, τ::T) where T
    return BarTerm(t.coef, t.word * τ)
end

"""
`*(σ::T, t::BarTerm{T}, τ::T) where T`
