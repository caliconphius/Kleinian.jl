function filtfact(
	B::GarsideMonoid{T},
	D::LCMGenData{T},  
	x::AbstractBarGen{T}, 
	σ::T
	) where T
	
	ω = D.gendata[x].product
	ωσ = ω * σ

	# Faire une version "unsafe" avec I = D.lcmdata[ωσ].left_descents ?
	I = haskey(D.lcmdata, ωσ) ? D.lcmdata[ωσ].left_descents : leftdescents(B, ωσ)
	i = getfirst(∈(I), D.gendata[x].right_lcmcs)

	if i === nothing
		(τ₁, τ₂) = (one(T), σ)
	else
		τ₁ = D.lcmdata[ω].right_lcmcs[i].comp
		τ₂ = \(B, τ₁, σ)
	end

	return (τ₁, τ₂)

end

function filtfact(
	B::GarsideMonoid{T}, 
	D::LCMGenData{T}, 
	x::AbstractBarGen{T}
	) where T
	
	n = length(x)

	if n == 0
		return T[one(T), one(T)]

	else
		for i ∈ 1:n
			(yᵢ, zᵢ) = filtfact(B, D, (@view x[1:i-1]), x[i])
			if zᵢ ≠ one(T) || i == n
				ϕx = T[
					j < i ? x[j] :
					j == i ? yᵢ :
					j == i+1 ? zᵢ :
					x[j-1]
					for j ∈ 1:n+1
				]
				return ϕx
			end
		end

	end

end

