function mem_sprint(B::GarsideMonoid{T}, σ::T ; ST::Dict{T, String}) where T
	haskey(ST, σ) && return ST[σ]
	ST[σ] = sprint(B, σ)
	return ST[σ]
end

function mem_sprint(B::GarsideMonoid{T}, x::AbstractBarGen{T} ; ST::Dict{T, String}, SB::Dict{BarGen{T}, String}) where T
	haskey(SB, x) && return SB[x]
	SB[x] = "[" * join((mem_sprint(B, σ ; ST) for σ ∈ x), "|") * "]"
	return SB[x]
end

function mem_sprint(B::GarsideMonoid{T}, u::BarWord{T} ; ST::Dict{T, String}, SB::Dict{BarGen{T}, String}) where T 
    return mem_sprint(B, u.left ; ST) * mem_sprint(B, u.gen ; ST, SB) * mem_sprint(B, u.right ; ST)
end

function mem_sprint(B::GarsideMonoid{T}, t::BarTerm{T} ; ST::Dict{T, String}, SB::Dict{BarGen{T}, String}) where T
    λ = t.coef
    w = mem_sprint(B, t.word ; ST, SB)
    λ == 1 && return " + $(w)"
    λ == -1 && return " - $(w)"
    return " + $(λ)·$(w)"
end

function mem_sprint(B::GarsideMonoid{T}, a::AbstractBarElt{T} ; ST::Dict{T, String}, SB::Dict{BarGen{T}, String}) where T
    isempty(a) && return "0"
    return join((mem_sprint(B, t ; ST, SB) for t ∈ a), "")
end


