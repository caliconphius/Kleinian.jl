LCMData{T} = Dict{T, LCMDataElement{T}}

function print_lcmdata(B::GarsideMonoid{T}, lcmdata::LCMData{T}) where T
	wordB(ω::T) where T = word(B, ω)
	for ω ∈ sort!(collect(keys(lcmdata)) ; by = wordB, lt = isless_deglex)
		ld = lcmdata[ω].left_descents
		if ld == collect(eachindex(B.atoms))
			sld = "1-$(length(B.atoms))"
		else
			sld = join([string(i) for i ∈ ld], ",")
		end
    	println("### ω = $(sprint(B, ω)), ld = $(sld) ###")
		print_right_lcmcs(B, lcmdata[ω].right_lcmcs)
		println()
	end
end

### full lcmdata ###

function full_lcm_data_element(B::GarsideMonoid{T}, ω::T) where T

	A = B.atoms
	
	ld = leftdescents(B, ω)
	maxdiv = isempty(ld) ? length(A)+1 : ld[end]
	
	rlcmc = Dict{Int, LCMC{T}}() 
	for i ∈ eachindex(A)[begin:(maxdiv-1)] if i ∉ ld
		ωᵢ, (τᵢ, _) = rightlcmc(B, ω, A[i])
		rlcmc[i] = LCMC{T}(ωᵢ, τᵢ)
	end end

	return LCMDataElement{T}(ld, rlcmc)

end

function full_lcm_data(B::GarsideMonoid{T}) where T

	lcmdata = LCMData{T}()
	lcms = [one(T)]

	for ω ∈ lcms
 		lcmdata[ω] = full_lcm_data_element(B, ω)
 		for l ∈ values(lcmdata[ω].right_lcmcs)
			if l.lcm ∉ lcms
 				push!(lcms, l.lcm)
 			end
 		end
 	end

	return lcmdata

end

### Orders using lcmdata ###

function ≼(lcmdata::LCMData{T}, ω::T, i::Int, j::Int) where T
	ωⱼ = lcmdata[ω].right_lcmcs[j].lcm
	Iⱼ = lcmdata[ωⱼ].left_descents
	return i ∈ Iⱼ
end

function isless_lex(B::GarsideMonoid{T}, lcmdata::LCMData{T}, σ::T, τ::T ; lt = <) where T
	if τ == one(T)
		return false
	elseif σ == one(T)
		return true
	else
		i = haskey(lcmdata, σ) ? lcmdata[σ].left_descents[1] : firstleftdescent(B, σ)
		j = haskey(lcmdata, τ) ? lcmdata[τ].left_descents[1] : firstleftdescent(B, τ)
		if lt(i, j)
			return true
		elseif i == j
			σ′ = \(B, B.atoms[i], σ)
			τ′ = \(B, B.atoms[j], τ)
			return isless_lex(B, lcmdata, σ′, τ′ ; lt)
		else # i > j
			return false
		end
	end
end

function isless_deglex(B::GarsideMonoid{T}, lcmdata::LCMData{T}, σ::T, τ::T ; lt = <) where T
	I = haskey(lcmdata, σ) ? lcmdata[σ].left_descents : leftdescents(B, σ)
	J = haskey(lcmdata, τ) ? lcmdata[τ].left_descents : leftdescents(B, τ)
	if is_included(J, I)
		return false
	elseif is_included(I, J)
		return true
	else # I et J incomparables
		return isless_lex(B, lcmdata, σ, τ ; lt)
	end
end

function isless_lex(B::GarsideMonoid{T}, lcmdata::LCMData{T}, ω::T, i::Int, j::Int ; lt = <) where T
	τᵢ = lcmdata[ω].right_lcmcs[i].comp
	τⱼ = lcmdata[ω].right_lcmcs[j].comp
	return isless_lex(B, lcmdata, τᵢ, τⱼ) || (τᵢ == τⱼ && lt(i, j))
end

function isless_deglex(B::GarsideMonoid{T}, lcmdata::LCMData{T}, ω::T, i::Int, j::Int ; lt = <) where T
	τᵢ = lcmdata[ω].right_lcmcs[i].comp
	τⱼ = lcmdata[ω].right_lcmcs[j].comp
	return isless_deglex(B, lcmdata, τᵢ, τⱼ) || (τᵢ == τⱼ && lt(i, j))
end

