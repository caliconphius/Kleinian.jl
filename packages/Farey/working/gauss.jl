"""
`filtered_lcm_complex(B::GarsideMonoid{T} ; filter::Bool=true, lex::Bool=true, A::AbstractVector{Int} = eachindex(B.atoms)) where T`
computes the (reduced) lcm resolution of the Garside monoid `B`. Optional keyword parameters allow to change the order used on atoms:
- `A`: vector giving the atoms 1,...,n in increasing order. Default to the natural order 1<...<n fixed by Chevie;
- `lex`: if `true` (default), compares atoms i and j using the lexicographic order on the right-complements of an atomic lcm ω in ω∨i and ω∨j; otherwise, uses the global order given by `A`;
- `filter`: if `true` (default), starts by comparing atoms i and j using the left-divisibility strict order ≺ on ω∨i and ω∨j, and then uses atom/lex if ω∨i and ω∨j are ≺-minimal.
Using `filter=false` and `lex=false` gives the original lcm resolution of Dehornoy-Lafont. Using `filter=true` and `lex=true` (default options) gives the reduced lcm resolution.
"""
function filtered_lcm_complex(B::GarsideMonoid{T} ; filter::Bool=true, lex::Bool=true, A::AbstractVector{Int} = eachindex(B.atoms)) where T

	D = lcm_gen_data(B ; filter, lex, A)
	X = D.generators
    d = filtered_lcm_differential(B, D)
	return (X, d)

end

