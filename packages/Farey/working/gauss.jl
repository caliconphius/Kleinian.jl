function minima(lcmdata::LCMData{T}, ω::T, I::AbstractVector{Int}) where T
	
	is_minimal = Bool[true for _ ∈ eachindex(I)]
	
	for k ∈ eachindex(I)[begin:end-1] if is_minimal[k]
		i = I[k]
		ωᵢ = lcmdata[ω].right_lcmcs[i].lcm
		for l ∈ eachindex(I)[k+1:end] if is_minimal[l]
			j = I[l]
			ωⱼ = lcmdata[ω].right_lcmcs[j].lcm
			if i ∈ lcmdata[ωⱼ].left_descents 
				is_minimal[l] = false
			elseif j ∈ lcmdata[ωᵢ].left_descents
				is_minimal[k] = false
				break
			end
		end end
	end end
	
	return Int[I[k] for k ∈ eachindex(I) if is_minimal[k]]

end

function minima_lt(lcmdata::LCMData{T}, ω::T, I::AbstractVector{Int}, ltω) where T
	
	is_minimal = Bool[true for _ ∈ eachindex(I)]
	
	for k ∈ eachindex(I)[begin:end-1] if is_minimal[k]
		i = I[k]
		ωᵢ = lcmdata[ω].right_lcmcs[i].lcm
		for l ∈ eachindex(I)[k+1:end] if is_minimal[l]
			j = I[l]
			ωⱼ = lcmdata[ω].right_lcmcs[j].lcm
			if i ∈ lcmdata[ωⱼ].left_descents && ltω(i, j)
				is_minimal[l] = false
			elseif j ∈ lcmdata[ωᵢ].left_descents && ltω(j, i)
				is_minimal[k] = false
				break
			end
		end end
	end end
	
	return Int[I[k] for k ∈ eachindex(I) if is_minimal[k]]

end



