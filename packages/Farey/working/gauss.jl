function format_time(time::Number)

	if time ≥ 3600

		(minutes, seconds) = fldmod(time, 60)
		(hours, minutes) = fldmod(minutes, 60)
	
		stime = @sprintf("%dh", hours)
		if minutes > 0
			stime = stime * @sprintf("%dmin", minutes)
		end

	elseif time ≥ 60

		(minutes, seconds) = fldmod(time, 60)
		seconds = floor(round(seconds))

		stime = @sprintf("%dmin", minutes)
		if seconds > 0
			stime = stime * @sprintf("%ds", seconds)
		end

	elseif time ≥ 1

		stime = @sprintf("%gs", round(time, sigdigits=3))

	elseif time ≥ 0.001

		stime = @sprintf("%gms", round(1000 * time, sigdigits=3))

	elseif time ≥ 0.000001

		stime = @sprintf("%gμs", round(1000000 * time, sigdigits=3))

	else

		stime = @sprintf("%gns", round(1000000000 * time, sigdigits=3))

	end

	return stime

end

function format_bytes(bytes::Number)

	units = ["B", "KiB", "MiB", "GiB", "TiB", "PiB", "EiB", "ZiB", "YiB"]

	i = 1
	unit = units[i]

	while bytes ≥ 1024
		if i == 9
			break
		else
			i = i + 1
			unit = units[i]
			bytes = bytes / 1024
		end
	end

	return @sprintf("%g%s", round(bytes, sigdigits=4), unit)

end


