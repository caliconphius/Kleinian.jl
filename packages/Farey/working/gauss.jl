### Checks for differentials ###

"""
`square(d::AbstractDict{BarGen{T},BarElt{T}}, x::AbstractBarGen{T}) where T`
returns `d`²(`x`).
"""
function square(d::AbstractDict{BarGen{T},BarElt{T}}, x::AbstractBarGen{T}) where T
	return normalise!(BarTerm{T}[
			t.coef * t.word.left * s * t.word.right
			for t ∈ d[x]
			for s ∈ d[t.word.gen]
		])
end

"""
`is_differential(d::AbstractDict{BarGen{T}, BarElt{T}}) where T`
checks if the linear map defined by the dictionary `d` is a differential, i.e. if `d`²(`x`) is equal to 0 for every key of `d`.
"""
function is_differential(d::AbstractDict{BarGen{T}, BarElt{T}}) where T
	return all([square(d, x) == zero(BarElt{T}) for x ∈ keys(d)])
end 

### Collapsing pairs of a complex ###

cells(d,n) = [x for x ∈ keys(d) if length(x) == n]

is_contractible(x) = length([y for y ∈ d[x] if y.word.left == one(Perm{Int16}) && y.word.right == one(Perm{Int16})]) ≥ 1

gens_trivial_coefs(d,y) = [ x.word.gen for x ∈ d[y] if x.word.left == one(Perm{Int16}) && x.word.right == one(Perm{Int16})]

"""
`collapsible_pairs(d::Dict{BarGen{T}, BarElt{T}})`
returns the list of collapsible pairs of the differential `d`.
"""
collapsible_pairs(d::Dict{BarGen{T}, BarElt{T}}) where T = [(x,y) for y ∈ keys(d) for x ∈ gens_trivial_coefs(d,y)]

function print_collapsible_pairs(B,d)
	for (x,y) ∈ sort!(collapsible_pairs(d))
       println(sprint(B,x) * "  " * sprint(B,y))
    end
end


