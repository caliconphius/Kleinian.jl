### Main functions ###

function lcm_gen_data_lcmcs(B::GarsideMonoid{T}, lcmdata::LCMData{T}, ω::T, I::AbstractVector{Int}) where T

	Lω = lcmdata[ω].right_lcmcs

	for i ∈ I if !haskey(Lω, i)
		ωᵢ, (τᵢ, _) = rightlcmc(B, ω, B.atoms[i])
		Lω[i] = LCMC{T}(ωᵢ, τᵢ)
		if !haskey(lcmdata, ωᵢ) 
			lcmdata[ωᵢ] = LCMDataElement{T}(
				leftdescents(B, ωᵢ),
				Dict{Int, LCMC{T}}()
			)
		end
	end end

end

"""
`lcm_gen_data(B::GarsideMonoid{T} ; filter::Bool = true, deglex::Bool = true, A::AbstractVector{Int} = eachindex(B.atoms)) where T`
computes all the data on lcms and generators required to construct the (reduced) lcm resolution of `B`.
"""
function lcm_gen_data(B::GarsideMonoid{T} ; filter::Bool = true, lex::Bool = true, A::AbstractVector{Int} = eachindex(B.atoms)) where T

	# Ordre global sur les atomes
	invA = inverse_permutation(A)
	lt = begin
		if issorted(A)
			(i::Int, j::Int) -> i < j
		else
			(i::Int, j::Int) -> invA[i] < invA[j]
		end
	end

	# Relations d'ordre currifiées
	isless_deglex_B(σ::T, τ::T) = isless_deglex(B, lcmdata, σ, τ ; lt)
	isless_deglex_B(ω::T, i::Int, j::Int) = isless_deglex(B, lcmdata, ω, i, j ; lt)
	isless_lex_B(ω::T, i::Int, j::Int) = isless_lex(B, lcmdata, ω, i, j ; lt)
	# lt(ω::T, i::Int, j::Int) = deglex ? isless_deglex_B(ω, i, j) : i<j
	lt_rel(ω::T, i::Int, j::Int) = lex ? isless_lex_B(ω, i, j) : lt(i, j)

	# Filtrage : enlever les i tq ∃ j ⊲_ω i tq j ≼ ωᵢ
	min!(ω::T, I::Vector{Int}, ltω) = if filter # V15a ou V15b
		# Enlever les i tq ∃j≠i avec j ≺ ωᵢ, ou ∃j<i avec ωⱼ = ωᵢ
		minima!(lcmdata, ω, I)
	elseif !lex # V15d
		# Enlever les i tq ∃j<i avec j ≼ ωᵢ
		minima_nonreduced!(lcmdata, ω, I)
	else #V15c -> donne la même chose que V15a, mais plus lentement
		# Enlever les i tq ∃ j ⊲_ω i avec j ≼ ωᵢ
		minima_lt!(lcmdata, ω, I, ltω)
	end

	# Initialisation
	X = BarGen{T}[one(BarGen{T})]

	lcmdata = LCMData{T}(
		one(T) => LCMDataElement{T}(Int[], Dict{Int, LCMC{T}}())
	)
	
	gendata = GenData{T}(
		one(BarGen{T}) => GenDataElement{T}(one(T), deepcopy(A))
	)

	# Calcul des générateurs
	for x ∈ X

 		ω = gendata[x].product
		ltω(i::Int, j::Int) = lt_rel(ω, i, j)

		Iₓ = gendata[x].right_lcmcs
		lcm_gen_data_lcmcs(B, lcmdata, ω, Iₓ)

		# Filtrer les éléments de Iₓ : 
		min!(ω, Iₓ, ltω)

		# Ordonner les atomes restants
		sort!(Iₓ ; lt = ltω)

		# Pour chaque atome i∈Iₓ restant :
		# - ajouter xᵢ = x|τᵢ aux générateurs
		# - créer une nouvelle clef xᵢ dans gendata : produit = ωᵢ, lcmcs = les j ⊲_ω i dans Iₓ
		for k ∈ eachindex(Iₓ)
			i = Iₓ[k]
			ωᵢ = lcmdata[ω].right_lcmcs[i].lcm
			τᵢ = lcmdata[ω].right_lcmcs[i].comp
			xᵢ = T[x..., τᵢ]
			Iᵢ = Iₓ[begin:k-1]

			push!(X, xᵢ)
			gendata[xᵢ] = GenDataElement{T}(ωᵢ, Iᵢ)
		end

	end

	# Tri des générateurs
	lt_gens(x, y) = isless_deglex(x, y ; lt = isless_deglex_B)
	sort!(X ; lt = lt_gens)

	return LCMGenData(X, lcmdata, gendata)

end

### Benchmarks lcmgendata ###

gauss = [:Gauss_a, :Gauss_b, :Gauss_d]
all_gauss = [:Gauss_a, :Gauss_b, :Gauss_c, :Gauss_d]
