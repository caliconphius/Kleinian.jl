"""
`Gar(B::GarsideMonoid{T}) where T`
computes the Garside complex of the Garside monoid `B`. Warning: the complex is huge!
"""
function Gar(B::GarsideMonoid{T}) where T

    nontrivial_simples = left_divisors(B, B.δ)[2:end]
    n = length(nontrivial_simples)

    X = Vector{BarGen{T}}[BarGen{T}[] for _ ∈ 1:n]

    println("Degré 1/$(n)")
    @time X[1] = BarGen{T}[T[σ] for σ ∈ vcat(nontrivial_simples...)]

    for i ∈ 2:n
        println("Degré $(i)/$(n)")
        @time for x ∈ X[i-1]
            ℓx = sum(reflength(B.W, ξ) for ξ∈x ; init = 0)
            πx = prod(x ; init = one(B.W))
            for ℓ ∈ 1:(n-ℓx)
                for σ ∈ nontrivial_simples[ℓ]
                    if B(πx * σ) == B(πx) * B(σ)
                        push!(X[i], T[x..., σ])
                    end
                end
            end
        end
    end

    return vcat([one(BarGen{T})], X...)

end

### Differential of the Bar/Garside complex ###

"""
`dgar(i::Int, x::AbstractBarGen{T}) where T`
is the simplicial `i`th face of the generator `x` of the Garside complex.
"""
function dgar(i::Int, x::AbstractBarGen{T}) where T
	n = length(x)
    if i==0
        return BarTerm{T}(1, BarWord(x[1], x[2:n], one(T)))
    elseif i==n
        return BarTerm{T}((-1)^n, BarWord(one(T), x[1:n-1], x[n]))
    else # 1≤i<N
		return BarTerm{T}((-1)^i, BarWord(view(x,1:i) · view(x,i+1:n)))
    end
end

"""
`dgar(x::AbstractBarGen{T}) where T`
is the boundary of the generator `x` in the Garside complex.
"""
function dgar(x::AbstractBarGen{T}) where T
    n = length(x)
	if n == 0
		return zero(BarElt{T})
	else
	    return BarTerm{T}[dgar(i,x) for i ∈ 0:n]	
	end
end

"""
`dgar_left(i::Int, x::AbstractBarGen{T}) where T`
is the left coefficient of the simplicial `i`th face of the generator `x` of the Garside complex.
"""
function dgar_left(i::Int, x::AbstractBarGen{T}) where T
	if i==0 
		return x[1]
	else
		return one(T)
	end
end

"""
`dgar_right(i::Int, x::AbstractBarGen{T}) where T`
is the right coefficient of the simplicial `i`th face of the generator `x` of the Garside complex.
"""
function dgar_right(i::Int, x::AbstractBarGen{T}) where T
	n = length(x)
	if i == n
		return x[n]
	else
		return one(T)
	end
end

"""
`dgar_gen(i::Int, x::AbstractBarGen{T}) where T`
is the generator in the simplicial `i`th face of the generator `x` of the Garside complex.
"""
function dgar_gen(i::Int, x::AbstractBarGen{T}) where T
	n = length(x)
	if i == 0
		return @view x[2:n]
	elseif i == n
		return @view x[1:n-1]
	else
		return @view ((@view x[1:i]) · (@view x[i+1:n]))[:]
	end
end

