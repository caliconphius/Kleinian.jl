function filtproj(
	B::GarsideMonoid{T},
	D::LCMGenData{T},
	x::AbstractBarGen{T}
	;
	fpdict::AbstractDict{BarGen{T}, BarElt{T}} 
		= Dict{BarGen{T}, BarElt{T}}(x => [BarTerm(BarWord(x))] for x ∈ D.generators)
	) where T

	# p(x) already computed, includes the case x ∈ X⁰
 	haskey(fpdict, x) && return fpdict[x]

	# else (implies x ∈ X⁻ or x ∈ X⁺)
	hₓ = @view x[1:end-1]
	xₙ = x[end]
		
	if haskey(D.gendata, hₓ) # hₓ ∈ X⁰
		(y, z) = filtfact(B, D, hₓ, xₙ)

		if y == one(T) 
			# hₓ ∈ X⁰, x ∈ X⁺ : p(x) = 0
			fpdict[x] = zero(BarElt{T})

		else 
			# hₓ ∈ X⁰, x ∈ X⁻ : p(x) = Σ_{1≤i≤n+1, i≠n} (-1)^{n+i+1} dᵢϕ(x)
			n = length(x)
			ϕx = T[
				i < n ? x[i] :
				i == n ? y :
				z
				for i ∈ 1:n+1
			]

			δᵢϕx = (
				(-1)^(n+1) * dgar(i, ϕx) 
				for i ∈ 0:n+1 if i ≠ n
			)

			fpdict[x] = zero(BarElt{T})
			for t ∈ δᵢϕx
				pt = t.coef * t.word.left * filtproj(B, D, t.word.gen ; fpdict) * t.word.right
				append!(fpdict[x], pt)
			end
			normalise!(fpdict[x])

		end

	else 
		# hₓ ∈ X⁻ or hₓ ∈ X⁺: p(x) = p( p(hₓ) ⊙ xₙ )
		fpdict[x] = zero(BarElt{T})
		for t ∈ filtproj(B, D, collect(hₓ) ; fpdict)
			y = t.word.gen | (t.word.right * xₙ)
			pt = t.coef * t.word.left * filtproj(B, D, y ; fpdict)
			append!(fpdict[x], pt)
		end
		normalise!(fpdict[x])

	end

	return fpdict[x]

end

