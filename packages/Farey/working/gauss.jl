
"""
This code contains work in progress towards a Julia package for homological computations on braid monoids, variants and generalisations. It replaces the former version Garside.jl, providing faster implementation and optimised constructions.

Gauss.jl contains functions to compute the lcm resolution of a Garside monoid B (called the "order resolution" in Dehornoy-Lafont [2003]), in the category of ZB-bimodules, and much improved versions of this resolution. The code relies on the Chevie package by Jean Michel (formerly Gapjm), and the author thanks him for explanations on the library and more generally for programming hints in Julia.

Garside monoids are constructed using Chevie functions, e.g. `coxgroup` or `crg` to generate a Coxeter group or a complex reflection group, then `BraidMonoid` or `DualBraidMonoid` to obtain the corresponding classical or dual braid monoid (if defined). Wrappers `braid_monoid` and `dual_braid_monoid` are provided (see examples below).

The main construction `filtered_lcm_complex(B::GarsideMonoid{T}) where T` returns a pair `(X, d)` containing the generators of the resolution and a dictionary with the values of the differential. The resolution is obtained by contraction of the Garside resolution using a collapsing scheme.
	
Examples of usage:

```julia-repl
julia> B = braid_monoid(:A, 6)
julia> (X, d) = filtered_lcm_complex(B);
```

```julia-repl
julia> B = dual_braid_monoid(:E, 7)
julia> (X, d) = filtered_lcm_complex(B ; filter = true, lex = true, A = eachindex(B.atoms), verbose = true);
```

```julia-repl
julia> W = crg(34)
julia> B = DualBraidMonoid(W)
julia> (X, d) = filtered_lcm_complex(B); 
```
"""

