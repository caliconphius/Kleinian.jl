"""
`isless_lex(u::AbstractVector{T}, v::AbstractVector{T}) where T`
returns true if `u` is strictly inferior to `v` for the (left) lexicographic order generated by a strict order `lt` on `T` (`lt` is `<` by default).
"""
function isless_lex(u::AbstractVector{T}, v::AbstractVector{T} ; lt = <) where T
	if length(v) == 0
		return false
	elseif length(u) == 0
		return true
	else
		return lt(u[1],v[1]) || (u[1]==v[1] && isless_lex((@view u[2:end]), (@view v[2:end]) ; lt))
	end
end

"""
`isless_deglex(u::AbstractVector{T}, v::AbstractVector{T}) where T`
returns true if `u` is strictly inferior to `v` for the (left) degree-wise lexicographic order generated by a strict order `lt` on `T` (`lt` is `<` by default): it first compares the length of `u` and `v` and, in case of equality, checks if `u` is striclty inferior to `v` for the lexicographic order.
"""
function isless_deglex(u::AbstractVector{T}, v::AbstractVector{T} ; lt = <) where T
	return length(u)<length(v) || (length(u)==length(v) && isless_lex(u,v ; lt))
end


