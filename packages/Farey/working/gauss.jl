### Elements of the free ZT-bimodule over BarGen{T} (linear combinations of BarTerm{T}s) ###

"""
`BarElt{T}` is the type of elements of the free Z`T`-bimodule over `BarGen{T}`, i.e. linear combinations of `BarTerm{T}s`. They are represented as vectors of `BarTerm{T}`s. The function `normalise!` is used to compute canonical forms.
"""
BarElt{T} = Vector{BarTerm{T}}

"""
`AbstractBarElt{T}` is used as a common generalisation of `BarElt{T}`s and views on them.
"""
AbstractBarElt{T} = AbstractVector{BarTerm{T}}

"""
`sprint(B::GarsideMonoid{T}, a::AbstractBarElt{T}) where T`
returns a string formed by the concatenation of all the `sprint(B,t)` for `t` a term of `a` (or `0` if `a` is empty).
"""
function sprint(B::GarsideMonoid{T}, a::AbstractBarElt{T}) where T
    if isempty(a)
        return "0"
    else
        return join((sprint(B,t) for t ∈ a), "")
    end
end

"""
`zero(::Type{BarElt{T}}) where T`
returns the zero element of type `BarElt{T}`, i.e. the empty vector of `BarTerm{T}`s.
"""
function zero(::Type{BarElt{T}}) where T
    return BarTerm{T}[]
end

"""
`normalise!(a::AbstractBarElt{T}) where T`
returns a canonical form for the vector `a` of `BarTerm{T}`s, with all terms ordered according to their `word` fields, and terms with the same `word` fields summed (and removed in case the result is 0).
"""
function normalise!(a::AbstractBarElt{T}) where T
	if !isempty(a)
		# sort!(a ; lt = ((s,t)->isless(s,t ; lt)))
		sort!(a)
		i = 1
		while i < length(a)
			λ = a[i].coef
			while i < length(a) && a[i+1].word == a[i].word
				λ = λ + a[i+1].coef
				deleteat!(a, i+1)
			end
			if λ == 0
				deleteat!(a, i)
			else
				a[i] = BarTerm{T}(λ, a[i].word)
				i = i+1
			end
		end
	end
	return a
end

"""
`add(a::AbstractBarElt{T}, b::AbstractBarElt{T}) where T`
returns the (canonical form of) the sum of `a` and `b`.
"""
function add(a::AbstractBarElt{T}, b::AbstractBarElt{T}) where T
	return normalise!(vcat(a, b))
end

"""
`add!(a::AbstractBarElt{T}, b::AbstractBarElt{T}) where T`
returns the (canonical form of) the sum of `a` and `b` in the variable `a`.
"""
function add!(a::AbstractBarElt{T}, b::AbstractBarElt{T}) where T
	return normalise!(append!(a, b))
end

"""
`substract(a::AbstractBarElt{T}, b::AbstractBarElt{T}) where T`
returns the (canonical form of) the difference of `a` and `b`.
"""
function substract(a::AbstractBarElt{T}, b::AbstractBarElt{T}) where T
	return add(a, (-1)*b)
end

function *(λ::Int, a::AbstractBarElt{T}) where T
	if λ == 0
		return zero(BarElt{T})
	else
		return BarTerm{T}[λ*t for t ∈ a]
	end
end

function *(σ::T, a::AbstractBarElt{T}) where T
	return BarTerm{T}[σ*t for t ∈ a]
end

function *(a::AbstractBarElt{T}, τ::T) where T
	return BarTerm{T}[t*τ for t ∈ a]
end

function *(σ::T, a::AbstractBarElt{T}, τ::T) where T
	return BarTerm{T}[σ*t*τ for t ∈ a]
end

function *(λ::Int, σ::T, a::AbstractBarElt{T}) where T
	return BarTerm{T}[λ*σ*t for t ∈ a]
end

function *(λ::Int, a::AbstractBarElt{T}, τ::T) where T
	return BarTerm{T}[λ*t*τ for t ∈ a]
end

function *(λ::Int, σ::T, a::AbstractBarElt{T}, τ::T) where T
	return BarTerm{T}[λ*σ*t*τ for t ∈ a]
end

function ⊙(a::AbstractBarElt{T}, σ::T) where T
	return normalise!(BarTerm{T}[t⊙σ for t ∈ a])
end

function ⊙(a::AbstractBarElt{T}, x::AbstractBarGen{T}) where T
	return normalise!(BarTerm{T}[t⊙x for t ∈ a])
end

