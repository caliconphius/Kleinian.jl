function benchmark_lcmgendata(B::GarsideMonoid{T} ; versions::Vector{Symbol} = gauss) where T
	
    # Garside (V0) #
	if :Garside ∈ versions

		GC.gc()

		print("Garside: ")

		timed_lcmgens = @timed lcm_generators(B)
		while timed_lcmgens.compile_time > 0
			timed_lcmgens = @timed lcm_generators(B)
		end
		X, _ = timed_lcmgens.value
		time_d = timed_lcmgens.time
		mem_d = timed_lcmgens.bytes
		
		println("$(format_time(time_d)), $(format_bytes(mem_d)), $(length(X)) generators")
		
	end

    # Gauss (V15) #
	options = Tuple{String, Bool, Bool}[]
	:Gauss_a ∈ versions && push!(options, ("Gauss_a", true, true))
	:Gauss_b ∈ versions && push!(options, ("Gauss_b", true, false))
	:Gauss_c ∈ versions && push!(options, ("Gauss_c", false, true))
	:Gauss_d ∈ versions && push!(options, ("Gauss_d", false, false))

	for (version, filter, lex) ∈ options

		GC.gc()

		print("$(version): ")

		timed_lcmgendata = @timed lcm_gen_data(B ; filter, lex)
		while timed_lcmgendata.compile_time > 0
			timed_lcmgendata = @timed lcm_gen_data(B ; filter, lex)
		end
		lcmgendata = timed_lcmgendata.value
		time = timed_lcmgendata.time
		mem = timed_lcmgendata.bytes

		println("$(format_time(time)), $(format_bytes(mem)), $(length(lcmgendata.gendata)) generators")

	end
	
end

