	@time println(io, join(("d($(mem_sprint(B, x ; ST, SB))) = $(mem_sprint(B, d[x] ; ST, SB))\n– number of terms: $(length(d[x]))" for x ∈ X⁰), "\n\n"))
	println()

	# Closing #

	println("Writing result in $(filename)")
	@time close(io)
	println()

	return nothing

end

function save_classic(TT::Symbol, n::Int...)

	coxtype_utf8 = "$(TT)$(sub(string(n)))"
	coxtype_ascii = "$(TT)_$(n[1])"
	if length(n) ≥ 2
		coxtype_utf8 = coxtype_utf8 * "($(n[2]))"
		coxtype_ascii = coxtype_ascii * "($(n[2]))"
	end

	B = braid_monoid(TT, n...)
	title = "### Reduced lcm resolution of B⁺($(coxtype_utf8)) ###"
	title = "#"^length(title) * "\n" * title * "\n" * "#"^length(title)
	filename = "results/classic/$(coxtype_ascii).txt"

	save_lcm_complex(B, title, filename)

	return nothing

end

function save_dual(TT::Symbol, n::Int... ; δ::AbstractVector{Int} = 1:n[1])

	coxtype_utf8 = "$(TT)$(sub(string(n)))"
	coxtype_ascii = "$(TT)_$(n[1])"
	if length(n) ≥ 2
		coxtype_utf8 = coxtype_utf8 * "($(n[2]))"
		coxtype_ascii = coxtype_ascii * "($(n[2]))"
	end
	delta = string(collect(δ))

	B = dual_braid_monoid(TT, n... ; δ)
	title = "### Reduced lcm resolution of B^*($(coxtype_utf8)), δ = $(delta) ###"
	title = "#"^length(title) * "\n" * title * "\n" * "#"^length(title)
	filename = "results/dual/$(coxtype_ascii).txt"

	save_lcm_complex(B, title, filename)

	return nothing

end

