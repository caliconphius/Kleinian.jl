"""
`getfirst(P::Function, X)`
takes a predicate `P(x::X)::Bool` and a collection `X`, and returns the first element `X[i]` of `X` such that `P(X[i])` is true. This is a variant of `findfirst`, which returns the index `i` instead of the value `X[i]`. When possible, use e.g. `getfirst(∈([1, 3, 5, 7]), [2, 3, 6, 8])` instead of `getfirst(i -> i ∈ [1, 3, 5, 7], [2, 3, 6, 8])` to avoid recompilation at each call of the function.
"""
function getfirst(P::Function, X)
	for x ∈ X
		P(x) && return x
	end
	return nothing
end

"""
`is_included(I::AbstractVector{T}, J::AbstractVector{T}) where T`
tests whether each value of `I` appears in `J` or not.
