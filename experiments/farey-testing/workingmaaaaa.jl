
"""
    commutator_collecting(generators::Vector{Symbol}, word::Vector{Tuple{Symbol,Int}}) -> Vector{Tuple{Symbol,Int}}

Perform the commutator collecting process on a word in the free group generated by `generators`.

The collecting process (also known as the Hall collection algorithm) rewrites a word
into a collected (normal) form by moving generators to the left using the commutator
identity:
    b * a = a * b * [b, a]
where [b, a] = b^{-1} * a^{-1} * b * a is the commutator of b and a.

# Arguments
- `generators`: ordered list of generators (e.g., [:a, :b, :c])
- `word`: list of (generator, exponent) pairs representing the input word

# Returns
A new word in collected form as a list of (generator, exponent) pairs,
where generators appear in the prescribed order with commutators appended.

# Example
```julia
generators = [:a, :b]
word = [(:b, 1), (:a, 1)]
result = commutator_collecting(generators, word)
# => [(:a, 1), (:b, 1), (:b, -1), (:a, -1), (:b, 1), (:a, 1)]
```
"""
function commutator_collecting(generators::Vector{Symbol}, word::Vector{Tuple{Symbol,Int}})
    # Build a rank map for generator ordering
    rank = Dict(g => i for (i, g) in enumerate(generators))

    # Expand word into a flat list of (symbol, ±1) letters for easier manipulation
    function expand(w::Vector{Tuple{Symbol,Int}})
        letters = Tuple{Symbol,Int}[]
        for (g, e) in w
            step = e > 0 ? 1 : -1
            for _ in 1:abs(e)
                push!(letters, (g, step))
            end
        end
        return letters
    end

    # Compress a flat letter list back into (symbol, exponent) pairs
    function compress(letters::Vector{Tuple{Symbol,Int}})
        result = Tuple{Symbol,Int}[]
        i = 1
        while i <= length(letters)
            g, e = letters[i]
            j = i + 1
            while j <= length(letters) && letters[j][1] == g
                e += letters[j][2]
                j += 1
            end
            if e != 0
                push!(result, (g, e))
            end
            i = j
        end
        return result
    end

    # Commutator [b, a] = b^{-1} a^{-1} b a as a flat letter list
    function commutator(b::Symbol, a::Symbol)
        return [(b, -1), (a, -1), (b, 1), (a, 1)]
    end

    # Main collecting loop: repeatedly find the leftmost out-of-order adjacent pair
    # and apply the commutator rewriting rule b·a → a·b·[b,a]
    letters = expand(word)

    changed = true
    iteration = 0
    while changed && iteration < 10
        changed = false
        i = 1
        while i < length(letters)
            (g1, e1) = letters[i]
            (g2, e2) = letters[i+1]
            # If two adjacent letters are out of order (rank of left > rank of right),
            # apply: g1^{e1} * g2^{e2}  →  g2^{e2} * g1^{e1} * [g1^{e1}, g2^{e2}]
            # For single letters (exponents ±1) use the basic commutator identity.
            if rank[g1] > rank[g2]
                # Remove the two letters and insert rewritten sequence
                comm = commutator(g1, e1 == 1 ? g1 : g1)   # placeholder expansion below
                # Rewrite: b·a  =>  a·b·[b,a]  where b=letters[i], a=letters[i+1]
                rewritten = vcat(
                    [(g2, e2)],
                    [(g1, e1)],
                    commutator(g1, g2) # [b, a] appended on the right
                )
                letters = vcat(letters[1:i-1], rewritten, letters[i+2:end])
                changed = true
                break
            end
            i += 1
        end
        iteration += 1
    end

    return compress(letters)
end


commutator_collecting([:a, :b], [(:b, 1), (:a, 1)])
